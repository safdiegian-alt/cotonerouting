import assert from 'node:assert/strict';
import {applyManualStops} from '../public/manual-stops.mjs';
const imported=[{id:1,key:'csv-a',np:'NP 1',type:'Entrega',address:'A'},{id:2,key:'csv-b',np:'NP 2',type:'Retiro',address:'B'}];
const edit={key:'manual:one',data:{kind:'manual',stop:{np:'NP 3',type:'Entrega',name:'Cliente',address:'C',city:'CABA',schedule:'9 a 17',service:15}}};
const hidden={key:'removed:csv-a',data:{kind:'removed',stopKey:'csv-a'}};
const result=applyManualStops(imported,[edit,hidden]);assert.equal(result.length,2);assert.equal(result[1].id,3);assert.deepEqual(result[1].windows,[[540,1020]]);assert.equal(imported.length,2);
assert.deepEqual(applyManualStops(imported,[edit,hidden]),result);
assert.equal(applyManualStops(imported,[edit,hidden,{data:{kind:'removed',stopKey:'manual:one'}}]).length,1);
assert.equal(applyManualStops([],[edit])[0].key,'manual:one');
console.log('PASS: manual additions, exclusions, reload stability, unique IDs, original import preserved.');
const {reorderStop}=await import('../public/manual-routing.mjs');
const {evaluate,scorePlan}=await import('../public/optimizer.mjs');
const items=[1,2,3].map(id=>({id,idx:id,np:'NP '+id,type:'Entrega',address:'Calle '+id,coord:[-34.6,-58.4+id*.01],windows:[[480,900]],service:15,lines:[]}));
const matrix={durations:Array.from({length:4},(_,i)=>Array.from({length:4},(_,j)=>i===j?0:60)),distances:Array.from({length:4},(_,i)=>Array.from({length:4},(_,j)=>i===j?0:100))};
const config={start:480,end:900,depotCoord:[-34.6,-58.4],depotAddress:'Base',twoTrips:false,flexibleStart:false};
const ctx={...config,...matrix,pickups:{}};
const plan={...scorePlan([evaluate(items,ctx)],[],[]),matrix,config};const snapshot=JSON.stringify(plan);
assert.deepEqual(reorderStop(plan,3,1).routes[0].route.map(s=>s.id),[3,1,2]);
assert.deepEqual(reorderStop(plan,1,'__end__').routes[0].route.map(s=>s.id),[2,3,1]);
assert.equal(JSON.stringify(plan),snapshot);
const pair=[{...items[0],np:'PAIR',type:'Retiro'},{...items[1],np:'PAIR',type:'Entrega'}];const pairPlan={...scorePlan([evaluate(pair,{...ctx,pickups:{PAIR:[1]}})],[],[]),matrix,config};
assert.throws(()=>reorderStop(pairPlan,2,1),/retiro antes de la entrega/);
assert.throws(()=>reorderStop(plan,3,999),/misma camioneta/);
console.log('PASS: explicit before/end ordering, unchanged input, pickup-before-delivery and target validation.');
